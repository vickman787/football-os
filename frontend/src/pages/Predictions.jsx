import { api } from '../lib/api.js';
import { useFetch } from '../lib/useFetch.js';
import { Loading, ErrorState, Skeleton } from '../components/States.jsx';

function Confidence({ value }) {
  const pct = Math.round(value * 100);
  return (
    <div style={{ flex: 1, marginLeft: 16 }}>
      <div className="bar"><span style={{ width: `${pct}%` }} /></div>
      <div style={{ fontFamily: 'var(--mono)', fontSize: 11, marginTop: 4, color: 'var(--text-dim)', letterSpacing: '0.16em', textTransform: 'uppercase' }}>
        Confidence {pct}%
      </div>
    </div>
  );
}

function MatchCard({ m }) {
  const k = new Date(m.kickoff);
  return (
    <div className="card match">
      <div className="match-head">
        <span>{m.league}</span>
        <span>{k.toUTCString().slice(0, 22)}</span>
      </div>
      <div className="match-teams">
        <span>{m.home.name}</span>
        <span className="vs">VS</span>
        <span>{m.away.name}</span>
      </div>
      <div className="pick-row">
        <span className="pick">{m.model.pick}</span>
        <Confidence value={m.model.confidence} />
      </div>
      <div className="probs">
        <div className="prob"><span className="l">Home</span><span className="v">{Math.round(m.model.probabilities.home * 100)}%</span></div>
        <div className="prob"><span className="l">Draw</span><span className="v">{Math.round(m.model.probabilities.draw * 100)}%</span></div>
        <div className="prob"><span className="l">Away</span><span className="v">{Math.round(m.model.probabilities.away * 100)}%</span></div>
      </div>
      <div className="probs">
        <div className="prob"><span className="l">xG Home</span><span className="v">{m.model.expectedGoals.home}</span></div>
        <div className="prob"><span className="l">xG Away</span><span className="v">{m.model.expectedGoals.away}</span></div>
        <div className="prob"><span className="l">Match Id</span><span className="v" style={{ fontSize: 10 }}>{m.id}</span></div>
      </div>
      <div className="reasoning">{m.model.reasoning}</div>
    </div>
  );
}

export default function Predictions() {
  const { data, error, loading, refetch } = useFetch(api.matches);
  const items = data?.matches ?? [];

  return (
    <>
      <div className="page-head">
        <span className="eyebrow">// AI Predictions</span>
        <h1 className="title">Model output for the next match window</h1>
        <p className="subtitle">
          Picks generated by the Football OS ensemble. Each call is hashable and ready to be
          anchored to X Layer from the wallet console.
        </p>
      </div>

      {error && <ErrorState error={error} onRetry={refetch} baseUrl={api.baseUrl} />}

      {loading && !error && (
        <>
          <Loading label="Fetching match models from /api/matches" />
          <div className="grid">
            <Skeleton height={260} />
            <Skeleton height={260} />
            <Skeleton height={260} />
          </div>
        </>
      )}

      {!loading && !error && items.length === 0 && (
        <div className="card"><p style={{ margin: 0, color: 'var(--text-dim)' }}>No matches in the current window.</p></div>
      )}

      {!loading && !error && items.length > 0 && (
        <div className="grid">
          {items.map((m) => <MatchCard key={m.id} m={m} />)}
        </div>
      )}
    </>
  );
}
